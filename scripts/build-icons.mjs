/**
 * Builds src/components/icons.generated.ts from the Tabler outline icons (MIT, https://tabler.io/icons),
 * the same way Study Desk does. Usage: node scripts/build-icons.mjs <path to @tabler/icons/icons/outline>
 * Only the icons listed in NAMES are bundled; keys are the names used with <Icon name="…"/>.
 */
import fs from 'node:fs';
import path from 'node:path';

const NAMES = {
  today: 'checklist', streaks: 'flame', typing: 'keyboard', week: 'calendar-week', shop: 'shopping-bag',
  settings: 'adjustments-horizontal', check: 'check', x: 'x', plus: 'plus', left: 'chevron-left', right: 'chevron-right',
  coin: 'coin', flame: 'flame', snow: 'snowflake', trophy: 'trophy', lock: 'lock', play: 'player-play', pause: 'player-pause',
  stop: 'player-stop', refresh: 'refresh', cloud: 'cloud', key: 'key', download: 'download', upload: 'upload', trash: 'trash',
  pen: 'pencil', undo: 'arrow-back-up', up: 'arrow-up', down: 'arrow-down', archive: 'archive', info: 'info-circle', moon: 'moon',
  sun: 'sun', gift: 'gift', star: 'star',
  // habit icons
  meditation: 'yoga', keyboard: 'keyboard', language: 'language', chart: 'chart-line', cards: 'cards', barbell: 'barbell',
  notebook: 'notebook', book: 'book', run: 'run', code: 'code', music: 'music', bed: 'bed', water: 'droplet', walk: 'walk',
};

const dir = process.argv[2];
if (!dir) throw new Error('Pass the path to @tabler/icons/icons/outline');
const out = {};
for (const [key, file] of Object.entries(NAMES)) {
  const svg = fs.readFileSync(path.join(dir, `${file}.svg`), 'utf8');
  out[key] = [...svg.matchAll(/<path\s+d="([^"]+)"\s*\/>/g)].map((m) => m[1]).join(' ');
  if (!out[key]) throw new Error(`${file}.svg has no plain paths`);
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
fs.writeFileSync(
  new URL('../src/components/icons.generated.ts', import.meta.url),
  `// Generated by scripts/build-icons.mjs from Tabler Icons 3.40.0 (MIT). Do not edit.\nexport const ICON_PATHS: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`${Object.keys(out).length} icons`);
